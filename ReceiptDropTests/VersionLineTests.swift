import XCTest
@testable import ReceiptDrop

/// Settings' last line is how anyone checks which build a device runs, so
/// it must be the bundle's real version and build, never a placeholder.
final class VersionLineTests: XCTestCase {
    func testVersionLineShowsTheBundlesVersionAndBuild() throws {
        let info = try XCTUnwrap(Bundle.main.infoDictionary)
        let version = try XCTUnwrap(info["CFBundleShortVersionString"] as? String)
        let build = try XCTUnwrap(info["CFBundleVersion"] as? String)
        XCTAssertTrue(SettingsView.versionLine.hasPrefix("Receipts4Tax \(version) (\(build))"))
        XCTAssertFalse(SettingsView.versionLine.contains("?"))
    }

    func testTheBuildDateIsStampedAndShown() throws {
        // Generated by the "Generate build date" build step on every build.
        let built = try XCTUnwrap(SettingsView.buildDate, "BuildInfo.builtAt isn't a valid date")
        XCTAssertLessThan(abs(built.timeIntervalSinceNow), 24 * 60 * 60, "should be this build, not a stale one")
        XCTAssertTrue(SettingsView.versionLine.contains("\nBuilt "))
    }
}
